def validate_generated_tree(destination: Path) -> None:
    kmn_files = sorted((destination / "source").glob("*.kmn"))
    if len(kmn_files) != 3:
        raise BuildError("the Keyman package must contain exactly three .kmn sources")
    kps = destination / "source" / f"{PACKAGE_ID}.kps"
    root = ET.fromstring(kps.read_text(encoding="utf-8"))
    keyboard_ids = [node.text for node in root.findall("./Keyboards/Keyboard/ID")]
    expected_ids = [
        PROFILE_METADATA[script]["keyboard_id"] for script in ("Deva", "Newa", "Limb")
    ]
    if keyboard_ids != expected_ids:
        raise BuildError(f"package keyboard IDs differ: {keyboard_ids}")
    languages = [node.attrib.get("ID") for node in root.findall(".//Language")]
    if languages != ["ne", "new-Newa", "lif-Limb"]:
        raise BuildError(f"package language tags differ: {languages}")


def build_tree(spec_path: Path, destination: Path) -> None:
    spec_bytes = spec_path.read_bytes()
    spec = mapping.read_json(spec_path)
    mapping.validate_spec(spec)
    source = destination / "source"
    source.mkdir(parents=True)
    for profile in spec["profiles"]:
        metadata = PROFILE_METADATA[profile["output_script"]]
        (source / f"{metadata['keyboard_id']}.kmn").write_text(
            render_kmn(profile), encoding="utf-8", newline="\n"
        )
    (source / f"{PACKAGE_ID}.kps").write_text(
        render_kps(spec), encoding="utf-8", newline="\n"
    )
    (source / "readme.htm").write_text(
        render_readme(spec), encoding="utf-8", newline="\n"
    )
    validate_generated_tree(destination)

    generated_files = sorted(path for path in source.rglob("*") if path.is_file())
    manifest = {
        "format_version": 1,
        "package_id": PACKAGE_ID,
        "package_version": spec["bundle"]["version"],
        "compiler": f"@keymanapp/kmc@{COMPILER_VERSION}",
        "minimum_keyman_version": "17.0",
        "profile_ids": [profile["profile_id"] for profile in spec["profiles"]],
        "spec_path": spec_path.relative_to(ROOT).as_posix(),
        "spec_sha256": sha256_bytes(spec_bytes),
        "files": [
            {
                "path": path.relative_to(destination).as_posix(),
                "sha256": sha256_bytes(path.read_bytes()),
                "size": path.stat().st_size,
            }
            for path in generated_files
        ],
    }
    (destination / "manifest.json").write_text(
        json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n",
        encoding="utf-8",
        newline="\n",
    )


def tree_snapshot(root: Path) -> dict[str, bytes]:
    if not root.is_dir():
        return {}
    return {
        path.relative_to(root).as_posix(): path.read_bytes()
        for path in sorted(root.rglob("*"))
        if path.is_file()
    }


def materialize(spec_path: Path, output: Path, check: bool) -> None:
    output.parent.mkdir(parents=True, exist_ok=True)
    temporary_parent = Path(tempfile.mkdtemp(prefix="nepa-keyman-", dir=output.parent))
    candidate = temporary_parent / "generated"
    candidate.mkdir()
    try:
        build_tree(spec_path, candidate)
        if check:
            expected = tree_snapshot(output)
            actual = tree_snapshot(candidate)
            if expected != actual:
                missing = sorted(set(actual) - set(expected))
                extra = sorted(set(expected) - set(actual))
                changed = sorted(
                    path for path in set(actual) & set(expected) if actual[path] != expected[path]
                )
                raise BuildError(
                    "generated Keyman sources are stale: "
                    f"missing={missing}, extra={extra}, changed={changed}"
                )
            return
        if output.exists():
            shutil.rmtree(output)
        os.replace(candidate, output)
    finally:
        shutil.rmtree(temporary_parent, ignore_errors=True)


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--spec", type=Path, default=DEFAULT_SPEC)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--check", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    materialize(args.spec.resolve(), args.output.resolve(), args.check)
    mode = "verified" if args.check else "built"
    print(f"Keyman Romanized Pro sources {mode}: {args.output.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
